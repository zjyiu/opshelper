export function getFileIcon(filename: string) {
  const ext = filename.split(".").pop()?.toLowerCase();
  switch (ext) {
    case "doc":
    case "docx":
      return <IconWord />;
    case "ppt":
    case "pptx":
      return <IconPPT />;
    case "xls":
    case "xlsx":
    case "csv":
      return <IconExcel />;
    case "md":
      return <IconMarkdown />;
    case "json":
      return <IconJSON />;
    case "pdf":
      return <IconPDF />;
    case "png":
    case "jpg":
    case "jpeg":
    case "gif":
    case "webp":
    case "svg":
    case "bmp":
      return <IconImage />;
    case "ts":
    case "tsx":
    case "js":
    case "jsx":
    case "py":
    case "sh":
    case "bash":
    case "yaml":
    case "yml":
    case "toml":
    case "xml":
    case "html":
    case "css":
    case "sql":
      return <IconCode />;
    case "zip":
    case "tar":
    case "gz":
    case "tgz":
    case "rar":
    case "7z":
      return <IconArchiveFile />;
    case "txt":
    case "log":
      return <IconTextDoc />;
    default:
      return <IconFile />;
  }
}
